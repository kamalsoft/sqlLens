import type { ReactNode } from "react";
import type { IndexRecommendation, ReviewV1, ReviewV2, RewriteStatus, SchemaVersion } from "@/lib/review-schema";
import {
  type Recommendation,
  RecommendationGroups,
  recommendationsFromV1,
  recommendationsFromV2,
} from "./RecommendationGroups";

export function Section({
  title,
  count,
  children,
}: {
  title: string;
  count?: number;
  children: ReactNode;
}) {
  return (
    <section className="review-report-section">
      <h3>
        {title}
        {count !== undefined && <span className="review-count">{count}</span>}
      </h3>
      {children}
    </section>
  );
}

function Table({ caption, head, rows }: { caption: string; head: string[]; rows: ReactNode[][] }) {
  return (
    <Section title={caption} count={rows.length}>
      {rows.length === 0 ? (
        <p className="review-empty">None reported.</p>
      ) : (
        <div className="review-table-wrap">
          <table aria-label={caption}>
            <thead>
              <tr>{head.map((h) => <th key={h} scope="col">{h}</th>)}</tr>
            </thead>
            <tbody>
              {rows.map((row, i) => (
                <tr key={i}>{row.map((cell, j) => <td key={j}>{cell}</td>)}</tr>
              ))}
            </tbody>
          </table>
        </div>
      )}
    </Section>
  );
}

function Badge({ value }: { value: string }) {
  return <span className={`review-badge review-badge-${value}`}>{value}</span>;
}

function Meta({ risk, confidence }: { risk?: string; confidence: number }) {
  return (
    <dl className="review-report-meta">
      {risk && (
        <div>
          <dt>Overall risk</dt>
          <dd><Badge value={risk} /></dd>
        </div>
      )}
      <div>
        <dt>Confidence</dt>
        <dd>{confidence > 0 ? `${Math.round(confidence * 100)}%` : "Not reported"}</dd>
      </div>
    </dl>
  );
}

export function IndexRecommendations({ items }: { items?: IndexRecommendation[] }) {
  // Older audit records have no indexRecommendations field.
  if (!items || items.length === 0) return null;
  return (
    <Section title="Index recommendations" count={items.length}>
      <p className="review-empty">
        Suggestions only. Check existing indexes, the execution plan and write load before creating any index.
      </p>
      <ul className="review-recommendations">
        {items.map((item, i) => (
          <li key={`${item.table}-${i}`}>
            <strong>{item.table}</strong>
            <p>
              Key: <code>{item.keyColumns.join(", ")}</code>
              {item.includeColumns.length > 0 && (
                <>
                  {" "}· Include: <code>{item.includeColumns.join(", ")}</code>
                </>
              )}
            </p>
            {item.reason && <p>{item.reason}</p>}
            {item.createStatement && <pre className="review-code">{item.createStatement}</pre>}
          </li>
        ))}
      </ul>
    </Section>
  );
}

const REWRITE_MESSAGES: Record<Exclude<RewriteStatus, "provided">, string> = {
  none: "The model did not recommend restructuring this procedure.",
  invalid: "The model's rewrite was not valid SQL that could run as written, so it was removed.",
  unsafe:
    "The model's rewrite was removed because it modifies data the original procedure does not. A restructure must keep the same writes.",
  truncated:
    "The rewrite was cut off at the new-token limit, so it was removed. Raise maxNewTokens in Settings to get the full rewrite.",
};

function Restructure({ result }: { result: ReviewV1 | ReviewV2 }) {
  const sql = result.rewrittenProcedure;
  // Older audit records have no rewriteStatus: show their rewrite if present.
  const status = result.rewriteStatus ?? (sql ? "provided" : undefined);
  if (!status) return null;
  const notes = result.rewriteNotes ?? [];
  return (
    <Section title="Recommended restructure">
      {status === "provided" ? (
        <>
          <p className="review-empty">
            Generated by the model; not executed or validated. Review and test it before deploying.
          </p>
          {notes.length > 0 && (
            <ul>
              {notes.map((note, i) => (
                <li key={i}>{note}</li>
              ))}
            </ul>
          )}
          <pre className="review-code" aria-label="Restructured procedure">{sql}</pre>
        </>
      ) : (
        <p className="review-empty" data-testid="rewrite-status">
          {REWRITE_MESSAGES[status]}
          {result.rewriteDetail && ` (${result.rewriteDetail}.)`}
        </p>
      )}
    </Section>
  );
}

export function ReviewResultView({
  schemaVersion,
  result,
  renderActions,
}: {
  schemaVersion: SchemaVersion;
  result: ReviewV1 | ReviewV2;
  renderActions?: (item: Recommendation) => ReactNode;
}) {
  if (schemaVersion === "v1") {
    const v1 = result as ReviewV1;
    return (
      <section className="review-report" aria-label="Review result v1">
        <Meta confidence={v1.confidence} />
        <Section title="Summary">
          <p>{v1.summary}</p>
        </Section>
        <Section title="Issues and recommendations" count={v1.issues.length}>
          <RecommendationGroups items={recommendationsFromV1(v1)} renderActions={renderActions} />
        </Section>
        <IndexRecommendations items={v1.indexRecommendations} />
        <Restructure result={v1} />
      </section>
    );
  }

  const v2 = result as ReviewV2;
  return (
    <section className="review-report" aria-label="Review result v2">
      <Meta risk={v2.overallRisk} confidence={v2.confidence} />
      <Section title="Summary">
        <p>{v2.summary}</p>
      </Section>
      <Section title="Recommendations" count={v2.findingsTable.length}>
        <RecommendationGroups items={recommendationsFromV2(v2)} renderActions={renderActions} />
      </Section>
      <Table
        caption="Findings"
        head={["Category", "Finding", "Evidence", "Severity", "Recommendation"]}
        rows={v2.findingsTable.map((r) => [
          r.category.replace(/_/g, " "),
          r.finding,
          <code key="e">{r.evidence}</code>,
          <Badge key="s" value={r.severity} />,
          r.recommendation,
        ])}
      />
      <Table
        caption="Performance"
        head={["Area", "Observation", "Evidence", "Impact", "Recommendation"]}
        rows={v2.performanceTable.map((r) => [
          r.area.replace(/_/g, " "),
          r.observation,
          <code key="e">{r.evidence}</code>,
          <Badge key="i" value={r.impact} />,
          r.recommendation,
        ])}
      />
      <Table
        caption="Security"
        head={["Area", "Observation", "Evidence", "Risk", "Recommendation"]}
        rows={v2.securityTable.map((r) => [
          r.area.replace(/_/g, " "),
          r.observation,
          <code key="e">{r.evidence}</code>,
          <Badge key="r" value={r.risk} />,
          r.recommendation,
        ])}
      />
      <Table
        caption="Testing"
        head={["Test", "Purpose", "Expected result"]}
        rows={v2.testingTable.map((r) => [r.test, r.purpose, r.expectedResult])}
      />
      <IndexRecommendations items={v2.indexRecommendations} />
      <Restructure result={v2} />
      {v2.limitations.length > 0 && (
        <Section title="Limitations" count={v2.limitations.length}>
          <ul>{v2.limitations.map((l, i) => <li key={i}>{l}</li>)}</ul>
        </Section>
      )}
    </section>
  );
}
